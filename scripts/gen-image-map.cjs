#!/usr/bin/env node
/*
  Generates src/imageMap.ts from card IDs in src/assets/data/cards.csv.
  For each id, it points to ./assets/cards/<id>.<ext> via new URL(..., import.meta.url).

  Behavior when sources are missing:
  - If CSV or cards directory is missing, it still writes src/imageMap.ts with an empty map
    so builds don’t fail.
*/

const fs = require('fs');
const path = require('path');

function parseCSV(raw) {
  const lines = raw.replace(/\r\n?/g, '\n').split('\n').filter(l => l.trim().length > 0);
  if (!lines.length) return [];
  const headers = splitCsvLine(lines[0]).map(h => h.trim());
  const rows = [];
  for (let i = 1; i < lines.length; i++) {
    const parts = splitCsvLine(lines[i]);
    const r = {};
    headers.forEach((h, idx) => { r[h] = (parts[idx] ?? '').trim(); });
    rows.push(r);
  }
  return rows;
}

function splitCsvLine(line) {
  const out = [];
  let cur = '';
  let inQuotes = false;
  for (let i = 0; i < line.length; i++) {
    const ch = line[i];
    if (inQuotes) {
      if (ch === '"') {
        if (line[i + 1] === '"') { cur += '"'; i++; } else { inQuotes = false; }
      } else cur += ch;
    } else {
      if (ch === ',') { out.push(cur); cur = ''; }
      else if (ch === '"') { inQuotes = true; }
      else cur += ch;
    }
  }
  out.push(cur);
  return out;
}

function idVariants(id) {
  // Normalize patterns like foo_bar_1 -> foo_bar1 (remove underscore before digits)
  const variants = new Set([id, id.replace(/_(\d+)/g, '$1')]);
  return Array.from(variants);
}

function main() {
  const root = process.cwd();
  const srcDir = path.join(root, 'src');
  const dataCsv = path.join(srcDir, 'assets', 'data', 'cards.csv');
  const cardsDirSrc = path.join(srcDir, 'assets', 'cards');
  const cardsDirRoot = path.join(root, 'assets', 'cards');
  const outTs = path.join(srcDir, 'imageMap.ts');
  const obfEnabled = process.env.IMG_OBF === '1';
  const obfManifestPath = path.join(root, 'public', 'assets', 'obf', 'manifest.json');

  let ids = [];
  if (fs.existsSync(dataCsv)) {
    const raw = fs.readFileSync(dataCsv, 'utf8');
    const rows = parseCSV(raw);
    ids = Array.from(new Set(rows.map(r => r.id).filter(Boolean)));
  }

  const exts = ['png', 'jpg', 'jpeg', 'svg'];
  const entries = [];

  // If obfuscation is enabled and manifest exists, read it so we can map ids to .bin files
  let obfManifest = null;
  if (obfEnabled && fs.existsSync(obfManifestPath)) {
    try {
      obfManifest = JSON.parse(fs.readFileSync(obfManifestPath, 'utf8')) || {};
    } catch {
      obfManifest = null;
    }
  }
  for (const id of ids) {
    if (obfManifest && obfManifest[id] && obfManifest[id].file) {
      // Obfuscated entry points to public path; no import necessary in TS map
      entries.push({ id, obfFile: obfManifest[id].file });
      continue;
    }
    let found = null;
    for (const cand of idVariants(id)) {
      for (const ext of exts) {
        const p1 = path.join(cardsDirSrc, `${cand}.${ext}`);
        const p2 = path.join(cardsDirRoot, `${cand}.${ext}`);
        if (fs.existsSync(p1)) { found = { id, ext, cand, where: 'src' }; break; }
        if (fs.existsSync(p2)) { found = { id, ext, cand, where: 'root' }; break; }
      }
      if (found) break;
    }
    if (!found) found = { id, ext: 'png', cand: id, where: 'src' };
    entries.push(found);
  }

  const header = `// Auto-generated by scripts/gen-image-map.cjs — do not edit\n`;
  const toVar = (id) => {
    const base = id.replace(/[^a-zA-Z0-9_]/g, '_');
    const safe = /^[A-Za-z_]/.test(base) ? base : `_${base}`;
    return `IMG_${safe}`;
  };
  let lines;
  if (obfManifest) {
    // Map directly to public obfuscated URLs. No ".png" strings in JS, only ".bin".
    const mapLines = entries.map((e) => `  '${e.id}': '/assets/obf/${e.obfFile}',`);
    lines = [
      header,
      `export const CARD_IMAGE_URLS: Record<string, string> = {`,
      ...mapLines,
      `};`,
      `export default CARD_IMAGE_URLS;`,
      ``,
    ];
  } else {
    const importLines = entries.map(({ id, ext, cand, where }) => {
      const rel = where === 'root' ? '../assets/cards' : './assets/cards';
      const v = toVar(id);
      return `import ${v} from '${rel}/${cand}.${ext}';`;
    });
    const mapLines = entries.map(({ id }) => `  '${id}': ${toVar(id)},`);
    lines = [
      header,
      ...importLines,
      '',
      `export const CARD_IMAGE_URLS: Record<string, string> = {`,
      ...mapLines,
      `};`,
      `export default CARD_IMAGE_URLS;`,
      ``,
    ];
  }

  // Ensure src exists and write file (even if entries is empty)
  fs.mkdirSync(srcDir, { recursive: true });
  fs.writeFileSync(outTs, lines.join('\n'));
  console.log(`[gen-image-map] Wrote ${entries.length} entries to`, path.relative(root, outTs));
}

main();
